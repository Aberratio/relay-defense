import type { EnemyKind, LevelDef, SpawnGroup } from '../engine/types';

/** One spawn group: `count` enemies of a kind, `gap` seconds apart. */
function g(
  enemy: EnemyKind,
  count: number,
  gap: number,
  opts: Omit<SpawnGroup, 'enemy' | 'count' | 'gap'> = {},
): SpawnGroup {
  return { enemy, count, gap, ...opts };
}

